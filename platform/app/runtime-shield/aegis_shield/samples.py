"""Generate Runtime Shield sample deliverables into output/sample_reports/runtime_shield/.

    PYTHONPATH=$(ls -d app/*/ | tr '\\n' ':') python3 -m aegis_shield.samples [--out DIR]

Each sample is labelled "Synthetic example".
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from aegis_common.evidence import find_prohibited_claims
from aegis_common.paths import OUTPUT_DIR

from .advisor import advise
from .examples import SAMPLES
from .generator import to_json, to_yaml
from .render import render_advice_markdown

SYNTHETIC_BANNER = "# Synthetic example — fictional organization and system generated by AEGIS for illustration.\n"


def write_samples(out_dir: str | Path | None = None) -> list[Path]:
    out = Path(out_dir) if out_dir else OUTPUT_DIR / "sample_reports" / "runtime_shield"
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for key, profile in SAMPLES.items():
        advice = advise(profile)
        md = render_advice_markdown(advice, synthetic_label=True)
        hits = find_prohibited_claims(md)
        if hits:
            raise RuntimeError(f"prohibited claims in sample {key}: {hits}")
        payload = {"label": "Synthetic example", "profile": profile, "advice": advice}
        files = {
            f"{key}_advisor.md": md,
            f"{key}_advisor.json": json.dumps(payload, indent=2, ensure_ascii=False),
            f"{key}_policy.yaml": SYNTHETIC_BANNER + to_yaml(advice["policy"]),
            f"{key}_policy.json": to_json({**advice["policy"],
                                           "metadata": {**advice["policy"]["metadata"],
                                                        "label": "Synthetic example"}}),
        }
        for name, text in files.items():
            p = out / name
            p.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")
            written.append(p)
    readme = out / "README.md"
    readme.write_text(
        "# Runtime Shield sample outputs (Synthetic example)\n\n"
        "Generated by `python3 -m aegis_shield.samples`. Organizations, systems and figures are fictional.\n\n"
        "| Profile | Advisor report | Advisor JSON | Draft policy |\n|---|---|---|---|\n"
        + "".join(f"| {k.replace('_', ' ')} | [{k}_advisor.md]({k}_advisor.md) | [{k}_advisor.json]({k}_advisor.json) | "
                  f"[{k}_policy.yaml]({k}_policy.yaml) / [{k}_policy.json]({k}_policy.json) |\n" for k in SAMPLES)
        + "\nPolicies are drafts in observe mode. They require review and recorded human approval before any "
          "promotion; AEGIS never activates a policy.\n",
        encoding="utf-8")
    written.append(readme)
    return written


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    for p in write_samples(args.out):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
