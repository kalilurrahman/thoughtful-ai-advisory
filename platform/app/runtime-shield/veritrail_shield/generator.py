"""Policy-as-code generator for the Runtime Shield Advisor.

``generate_policy(profile, advice=None) -> dict`` produces a policy that is valid
per ``veritrail_policy.schema`` and always:

* ``status: draft`` with no approvals recorded (approvals bind to a reviewed version);
* ``rollout.mode: observe`` with shadow evaluation as ``enforce``;
* default-deny for tools; denied tools listed explicitly on the deny-list;
* immutable audit logging with redacted/metadata-only content logging.

Versioning helpers (``bump_version``, ``new_version``, ``diff_policies``,
``record_change``, ``add_approval``, ``transition_status``) are re-exported from
``veritrail_policy.versioning``.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

import yaml

from veritrail_policy.constants import SCHEMA_VERSION
from veritrail_policy.schema import validate_policy
from veritrail_policy.versioning import (  # noqa: F401  (re-exported)
    add_approval,
    bump_version,
    diff_policies,
    new_version,
    record_change,
    summarize_diff,
    transition_status,
)

from .profile import normalize_profile, slug

GENERATOR_AUTHOR = "VERITRAIL Runtime Shield Advisor (automated draft)"
INITIAL_VERSION = "0.1.0"


def _today() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def _rule_from_entry(m: dict) -> dict:
    rule = {
        "id": f"tool.{slug(m['tool'], 80)}",
        "tool": m["tool"],
        "operation": m["operation"],
        "action": m["engine_action"],
        "description": "; ".join(m["reasons"]),
        "scopes": m["scopes"],
        "parameters": m["parameters"],
        "additional_parameters": not m["strict_parameters"],
        "citations": m["citations"],
    }
    if m["require_approval_if"]:
        rule["require_approval_if"] = m["require_approval_if"]
    if m["approval_roles"]:
        rule["approval_roles"] = m["approval_roles"]
    if m["max_calls_per_session"]:
        rule["max_calls_per_session"] = int(m["max_calls_per_session"])
    if m["allow_pii_entities"]:
        rule["allow_pii_entities"] = m["allow_pii_entities"]
    return rule


def generate_policy(profile: dict, advice: dict | None = None) -> dict:
    """Generate a draft runtime policy from a profile (and optionally precomputed advice)."""
    if advice is None or "tool_matrix" not in advice:
        from .advisor import analyze
        advice = analyze(profile or {})
    n = advice.get("_normalized") or normalize_profile(profile or {})
    risk = advice["risk_profile"]
    rating = risk["overall"]["rating"]
    tier = risk["user_asserted_risk_tier"] or risk["inferred_risk_tier"]
    dh = advice["data_handling"]
    limits = advice["limits"]
    ir = advice["incident_response"]

    rules, deny_list, seen = [], [], set()
    for m in advice["tool_matrix"]:
        if m["tool"] in seen:
            continue
        seen.add(m["tool"])
        if m["decision"] == "denied":
            deny_list.append(m["tool"])
        else:
            rules.append(_rule_from_entry(m))

    transforms = [{"id": "transform.truncate_response", "type": "truncate", "apply_to": ["response"],
                   "max_chars": 16000}]
    citations = {"IS-04", "IS-11", "IS-12", "IS-14", "IS-15", "IS-16", "SE-08", "EI-07", "GL-04"}
    if n["affected_parties"] in ("customers", "public", "vulnerable"):
        transforms.append({"id": "transform.ai_disclosure", "type": "append_disclosure", "apply_to": ["response"],
                           "text": "This response was generated with AI assistance."})
        citations.add("IS-08")
    link_domains = n.get("allowed_link_domains")
    if link_domains:
        transforms.append({"id": "transform.strip_unapproved_urls", "type": "strip_unapproved_urls",
                           "apply_to": ["response"], "domain_allow_list": list(link_domains)})
    for r in rules:
        citations.update(r["citations"])
        if r["action"] == "REQUIRE_HUMAN_APPROVAL" or r.get("require_approval_if"):
            citations.add("IS-13")

    approvers = advice.get("policy_approver_roles") or ["AI System Owner", "Security Lead"]
    stage1 = advice["rollout"]["stages"][0]
    policy = {
        "schema_version": SCHEMA_VERSION,
        "policy_id": f"pol-{slug(n['agent_name'], 70)}",
        "policy_name": f"{n['app_name']} — Runtime Policy",
        "description": (f"Draft runtime policy generated by VERITRAIL for {n['app_name']}"
                        + (f" ({n['purpose']})" if n["purpose"] else "")
                        + f". Overall runtime risk: {rating} (Inferred). Review before rollout."),
        "version": INITIAL_VERSION,
        "status": "draft",
        "owner": n["owner"],
        "applies_to": {
            "agent_name": [n["agent_name"]],
            "environment": [n["environment"]],
            "risk_tier": [tier],
            "tenant": [n["tenant"]],
            "model": [str(n["model"])] if n["model"] else ["*"],
        },
        "rollout": {
            "mode": "observe",
            "exit_criteria": stage1["exit_criteria"],
            "notes": advice["rollout"]["promotion_rule"],
        },
        "identity": {
            "required": True,
            "required_claims": ["sub", "tenant_id", "roles"],
            "allowed_roles": n["allowed_roles"],
            "tenant_binding": True,
        },
        "tools": {"default_action": "DENY", "deny_list": deny_list, "rules": rules},
        "content": {
            "max_input_chars": 32000 if rating in ("Low", "Medium") else 16000,
            "pii_redaction": {"enabled": True, "entities": dh["redaction_entities"],
                              "apply_to": dh["redaction_surfaces"], "action": "REDACT"},
            "prompt_injection": {"enabled": True, "apply_to": ["prompt", "tool_output", "tool_params"],
                                 "action": "DENY", "decode_obfuscation": True},
            "jailbreak": {"enabled": True, "apply_to": ["prompt"], "action": "DENY", "decode_obfuscation": True},
            "transforms": transforms,
        },
        "limits": {k: limits[k] for k in ("requests_per_minute", "tool_calls_per_session", "tokens_per_day",
                                          "cost_per_month_usd", "action_on_breach", "alert_at_percent")},
        "logging": {
            "immutable_audit": True,
            "prompt_logging": dh["prompt_logging"],
            "response_logging": dh["response_logging"],
            "tool_param_logging": "redacted",
            "sink": "veritrail_common.audit.AuditLog (hash-chained JSONL); ship to WORM storage in production",
        },
        "kill_switch": {
            "enabled": True,
            "engaged": False,
            "scopes": ir["kill_switch"]["scopes"],
            "engaged_targets": [],
            "authorized_roles": ir["kill_switch"]["authorized_roles"],
            "target_time_to_disable_minutes": ir["kill_switch"]["target_time_to_disable_minutes"],
        },
        "rollback": {
            "previous_version": None,
            "strategy": "disable",
            "triggers": [p["trigger"] for p in ir["playbooks"]],
        },
        "shadow_mode": {"enabled": True, "evaluate_as": "enforce"},
        "evidence_retention_days": dh["evidence_retention_days"],
        "approval": {
            "required_approver_roles": approvers,
            "min_approvers": len(approvers),
            "separation_of_duties": True,
            "approved_by": [],
            "approved_at": None,
        },
        "escalation": {"queue": ir["escalation"]["queue"], "contact_role": ir["escalation"]["contact_role"]},
        "change_history": [{
            "version": INITIAL_VERSION, "date": _today(), "author": GENERATOR_AUTHOR, "change_type": "created",
            "summary": "Initial draft generated from the Runtime Shield Advisor profile; requires human review.",
        }],
        "citations": sorted(citations),
        "metadata": {
            "generated_by": "veritrail_shield.generator",
            "advisor_version": advice.get("advisor_version"),
            "evidence_status": "Inferred",
            "overall_risk": rating,
            "requires_human_approval": True,
            "synthetic": n["synthetic"],
            "denied_tools": [{"tool": m["tool"], "reasons": m["reasons"]}
                             for m in advice["tool_matrix"] if m["decision"] == "denied"],
            "notice": ("Draft generated by VERITRAIL. VERITRAIL does not activate policies: promotion beyond draft/observe "
                       "requires review and recorded human approval. Detection is heuristic."),
        },
    }
    errors = validate_policy(policy)
    if errors:  # generator bug, never silently emit an invalid policy
        raise ValueError("generated policy failed validation: " + "; ".join(errors))
    return policy


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def to_yaml(policy: dict) -> str:
    header = (f"# VERITRAIL runtime policy {policy.get('policy_id')} v{policy.get('version')} "
              f"(status: {policy.get('status')})\n"
              "# Draft policies require review and recorded human approval before activation.\n")
    return header + yaml.dump(policy, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)


def to_json(policy: dict) -> str:
    return json.dumps(policy, indent=2, ensure_ascii=False)


def from_yaml(text: str) -> dict:
    return yaml.safe_load(text)


def from_json(text: str) -> dict:
    return json.loads(text)
