export function clinicalDocumentationScore(answers: Record<string, number>) {
  const done = CLINICAL_DOCUMENTATION_ROUNDS.filter((round) => answers[round.id] !== undefined);
  return {
    attempted: done.length,
    correct: done.filter((round) => answers[round.id] === round.best).length,
    complete: done.length === CLINICAL_DOCUMENTATION_ROUNDS.length,
  };
}
