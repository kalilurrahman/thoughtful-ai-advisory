/*
 * Synthetic sample deliverables — browser port of platform/scripts/generate_samples.py
 * (maturity reports + risk-tier results) and platform/app/runtime-shield/aegis_shield/samples.py
 * (Runtime Shield advice + draft policies).
 *
 * Everything produced here is SYNTHETIC — fictional organizations, self-reported answers — and is
 * labelled as such. It demonstrates the product; it is not evidence about any real organization.
 * Pure: no DOM, no I/O. The gallery turns the returned files into downloads (and PDFs).
 */
import { buildAssessmentBundle, scoreAssessment } from "@/features/site/engines/assessment-engine";
import { calculateRiskTier } from "@/features/site/engines/risk-tier";
import { advise, toJson as policyToJson, toYaml as policyToYaml } from "@/features/site/engines/shield";
import { findProhibitedClaims } from "@/features/site/engines/ask-aegis/safety";
import { pyFloatStr } from "@/features/site/engines/shield/py";
import { renderMaturityMarkdown } from "../reports/maturity";
import { PERSONAS, SHIELD_SAMPLES, USE_CASES } from "./personas";
import { renderAdviceMarkdown } from "./shield-render";

/** Fixed generation date used by the committed samples. */
export const SAMPLE_DATE = "2026-10-21";

export const BANNER =
  "> **Synthetic example.** Fictional organization and self-reported answers generated to demonstrate " +
  "AEGIS outputs. Not evidence about any real organization.\n\n";

export const SYNTHETIC_POLICY_BANNER =
  "# Synthetic example — fictional organization and system generated by AEGIS for illustration.\n";

export type SampleKind = "markdown" | "json" | "yaml";

export interface SampleFile {
  /** Path relative to platform/output/sample_reports, e.g. "maturity/example_bank_developing.md". */
  path: string;
  kind: SampleKind;
  content: string;
  /** Title used for the PDF header band (Markdown files only). */
  pdfTitle?: string;
}

export interface SampleGroup {
  id: "maturity" | "risk_tier" | "runtime_shield";
  title: string;
  files: SampleFile[];
}

type PathPred = (path: ReadonlyArray<string | number>) => boolean;

/**
 * json.dumps(obj, indent=2, ensure_ascii=False). JavaScript has no int/float distinction, so the
 * caller says which paths hold Python floats (printed as `60.0` rather than `60`).
 */
export function pyJsonDumps(obj: unknown, isFloat: PathPred = () => false, indent = 2): string {
  const walk = (v: unknown, path: Array<string | number>, depth: number): string => {
    const pad = " ".repeat(indent * (depth + 1));
    const end = " ".repeat(indent * depth);
    if (v === null || v === undefined) return "null";
    if (typeof v === "number") {
      if (!Number.isFinite(v)) return Number.isNaN(v) ? "NaN" : v > 0 ? "Infinity" : "-Infinity";
      return isFloat(path) ? pyFloatStr(v) : String(v);
    }
    if (typeof v === "boolean" || typeof v === "string") return JSON.stringify(v);
    if (Array.isArray(v)) {
      if (!v.length) return "[]";
      return `[\n${v.map((x, i) => pad + walk(x, [...path, i], depth + 1)).join(",\n")}\n${end}]`;
    }
    const entries = Object.entries(v as Record<string, unknown>).filter(([, x]) => x !== undefined);
    if (!entries.length) return "{}";
    return `{\n${entries
      .map(([k, x]) => `${pad}${JSON.stringify(k)}: ${walk(x, [...path, k], depth + 1)}`)
      .join(",\n")}\n${end}}`;
  };
  return walk(obj, [], 0);
}

/** Float-valued fields of an assessment result (domain scores, readiness values, overall). */
export const maturityFloatPaths: PathPred = (p) => {
  const last = p[p.length - 1];
  if (last === "overall_score") return true;
  const i = p.indexOf("domains");
  if (i >= 0 && p.length === i + 3 && last === "score") return true;
  const r = p.indexOf("readiness");
  return r >= 0 && p[r + 2] === "groups" && last === "value";
};

/** write_json(obj): json.dump(indent=2, ensure_ascii=False) + "\n". */
function writeJson(obj: unknown, isFloat?: PathPred): string {
  return pyJsonDumps(obj, isFloat) + "\n";
}

function ensureNewline(s: string): string {
  return s.endsWith("\n") ? s : s + "\n";
}

export function generateMaturitySamples(generated = SAMPLE_DATE): SampleGroup {
  const bundle = buildAssessmentBundle();
  const files: SampleFile[] = [];
  const index = [
    "# Sample maturity reports (synthetic)",
    "",
    "| Organization | Score | Level | Critical flags | Files |",
    "|---|---|---|---|---|",
  ];
  for (const p of PERSONAS) {
    const r = scoreAssessment(p.answers, p.profile, bundle);
    const md = BANNER + renderMaturityMarkdown(r, bundle, p.lead, generated);
    const title = `AI Governance Maturity Report — ${p.lead.company}`;
    files.push({ path: `maturity/${p.slug}.md`, kind: "markdown", content: md, pdfTitle: title });
    files.push({
      path: `maturity/${p.slug}.json`,
      kind: "json",
      content: writeJson({
        synthetic: true,
        lead: p.lead,
        profile: p.profile,
        answers: p.answers,
        result: r,
      }, maturityFloatPaths),
    });
    index.push(
      `| ${p.lead.company} | ${r.overall_score} | ${r.maturity_level} | ${r.critical_flags.length} | ` +
        `[md](${p.slug}.md) · [pdf](${p.slug}.pdf) · [json](${p.slug}.json) |`,
    );
  }
  files.unshift({
    path: "maturity/README.md",
    kind: "markdown",
    content: index.join("\n") + "\n",
    pdfTitle: "Sample maturity reports (synthetic)",
  });
  return { id: "maturity", title: "Maturity self-assessment reports", files };
}

export function generateRiskTierSamples(): SampleGroup {
  const files: SampleFile[] = Object.entries(USE_CASES).map(([k, prof]) => ({
    path: `risk_tier/${k}.json`,
    kind: "json" as const,
    content: writeJson({ synthetic: true, profile: prof, result: calculateRiskTier(prof) }),
  }));
  return { id: "risk_tier", title: "Preliminary AI risk-tier results", files };
}

export function generateShieldSamples(today = SAMPLE_DATE): SampleGroup {
  const files: SampleFile[] = [];
  const keys = Object.keys(SHIELD_SAMPLES);
  for (const key of keys) {
    const profile = SHIELD_SAMPLES[key] ?? {};
    const advice = advise(profile, { today });
    const md = renderAdviceMarkdown(advice, { syntheticLabel: true });
    const hits = findProhibitedClaims(md);
    if (hits.length) throw new Error(`prohibited claims in sample ${key}: ${hits.join(" | ")}`);
    const policy = advice.policy;
    files.push({
      path: `runtime_shield/${key}_advisor.md`,
      kind: "markdown",
      content: ensureNewline(md),
      pdfTitle: `AEGIS Runtime Shield Advisor — ${String(profile["app_name"] ?? key)}`,
    });
    files.push({
      path: `runtime_shield/${key}_advisor.json`,
      kind: "json",
      content: ensureNewline(
        JSON.stringify({ label: "Synthetic example", profile, advice }, null, 2),
      ),
    });
    files.push({
      path: `runtime_shield/${key}_policy.yaml`,
      kind: "yaml",
      content: ensureNewline(SYNTHETIC_POLICY_BANNER + policyToYaml(policy)),
    });
    files.push({
      path: `runtime_shield/${key}_policy.json`,
      kind: "json",
      content: ensureNewline(
        policyToJson({
          ...policy,
          metadata: { ...policy.metadata, label: "Synthetic example" },
        } as typeof policy),
      ),
    });
  }
  const readme =
    "# Runtime Shield sample outputs (Synthetic example)\n\n" +
    "Generated by `python3 -m aegis_shield.samples`. Organizations, systems and figures are fictional.\n\n" +
    "| Profile | Advisor report | Advisor JSON | Draft policy |\n|---|---|---|---|\n" +
    keys
      .map(
        (k) =>
          `| ${k.replace(/_/g, " ")} | [${k}_advisor.md](${k}_advisor.md) | [${k}_advisor.json](${k}_advisor.json) | ` +
          `[${k}_policy.yaml](${k}_policy.yaml) / [${k}_policy.json](${k}_policy.json) |\n`,
      )
      .join("") +
    "\nPolicies are drafts in observe mode. They require review and recorded human approval before any " +
    "promotion; AEGIS never activates a policy.\n";
  files.push({
    path: "runtime_shield/README.md",
    kind: "markdown",
    content: readme,
    pdfTitle: "Runtime Shield sample outputs (Synthetic example)",
  });
  return { id: "runtime_shield", title: "Runtime Shield advice and draft policies", files };
}

/** Regenerate every synthetic sample group. */
export function generateSamples(date = SAMPLE_DATE): SampleGroup[] {
  return [generateMaturitySamples(date), generateRiskTierSamples(), generateShieldSamples(date)];
}

export function fileName(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}
